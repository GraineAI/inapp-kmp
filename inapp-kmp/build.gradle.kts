/**
 * THE GATE BETWEEN THIS CODE AND A PUBLIC REGISTRY — the rules every Graine
 * package is held to (sdk/scripts/leak-rules.mjs), run over what ships: the
 * AAR and every sources jar, whose comments are published. (The Central bundle
 * is read again as a whole by `mavenCentralBundle`.)
 */
val verifyPackage by tasks.registering(Exec::class) {
    description = "Refuses to publish if the AAR or a sources jar carries anything internal."
    group = "publishing"
    dependsOn("bundleReleaseAar")
    dependsOn(tasks.matching { it.name.endsWith("SourcesJar") })
    val guard = rootProject.file("../scripts/verify-native-package.mjs")
    onlyIf { guard.exists() }
    doFirst {
        val archives = layout.buildDirectory.dir("libs").get().asFile.listFiles { f -> f.name.endsWith("-sources.jar") }.orEmpty().map { it.path } +
            layout.buildDirectory.file("outputs/aar/inapp-kmp-release.aar").get().asFile.path
        commandLine(listOf("node", guard.path) + archives)
    }
}
tasks.matching { it.name.startsWith("publish") }.configureEach { dependsOn(verifyPackage) }
