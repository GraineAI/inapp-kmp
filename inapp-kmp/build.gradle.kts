import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.tasks.KotlinCompileCommon
import org.jetbrains.kotlin.gradle.tasks.KotlinNativeCompile

plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("com.android.library")
    `maven-publish`
}

version = providers.gradleProperty("GRAINE_VERSION").get()

/**
 * The iOS targets need a Mac with Xcode, and Kotlin/Native's own toolchain the
 * first time. `-Pgraine.kmp.ios=false` builds and tests the Android side alone —
 * the shared code is compiled and tested there too. Never publish that way.
 */
val iosEnabled = providers.gradleProperty("graine.kmp.ios").orNull != "false"

/*
 * THE SHARED CONTRACT'S HISTORY VECTORS, FOR THE TESTS ON EVERY PLATFORM.
 * sdk/contract/history.json is vendored at src/commonTest/contract/history.json
 * — the exported repository carries no contract folder; HistoryVendoredTest
 * holds the copy equal to the contract's — and handed to the common tests as a
 * Kotlin string, since a Kotlin/Native test binary cannot read the source tree.
 */
val contractVectors by tasks.registering {
    val vendored = layout.projectDirectory.file("src/commonTest/contract/history.json")
    val out = layout.buildDirectory.dir("generated/contract/kotlin")
    inputs.file(vendored).withPathSensitivity(PathSensitivity.NONE)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("ai/graine/inapp/kmp")
        dir.deleteRecursively()
        dir.mkdirs()
        val dollar = "$"
        val text = vendored.asFile.readText().replace(dollar, "$dollar{'$dollar'}")
        dir.resolve("HistoryJson.kt").writeText(
            "package ai.graine.inapp.kmp\n\n" +
                "/** sdk/contract/history.json, as vendored in src/commonTest/contract. Generated by contractVectors: never edit. */\n" +
                "internal val HISTORY_JSON: String = \"\"\"$text\"\"\"\n"
        )
    }
}

kotlin {
    // expect/actual objects (the push hand-off) are stable enough for this; the flag only quiets the notice.
    compilerOptions { freeCompilerArgs.add("-Xexpect-actual-classes") }

    androidTarget {
        publishLibraryVariants("release")
        compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
    }

    if (iosEnabled) {
        listOf(iosX64(), iosArm64(), iosSimulatorArm64()).forEach { target ->
            // The iOS SDK's Objective-C facade (GraineObjC, sdk/ios/Sources/GraineInApp/ObjC), as its
            // header declares it. Only the header: the app links the SDK itself, with CocoaPods or
            // SwiftPM, so the library never carries a second copy of it (README → iOS).
            target.compilations.getByName("main").cinterops.create("GraineObjC") {
                definitionFile.set(project.file("src/nativeInterop/cinterop/GraineObjC.def"))
                packageName = "ai.graine.inapp.kmp.objc"
                includeDirs(project.file("src/nativeInterop/cinterop"))
            }
            // An iOS test binary links the iOS SDK it calls: a static build of sdk/ios for the
            // simulator, whose linker options scripts/ios-test-library.sh prints.
            providers.gradleProperty("graine.iosTestLinkerOpts").orNull?.let { opts ->
                target.binaries.withType<org.jetbrains.kotlin.gradle.plugin.mpp.TestExecutable>().configureEach {
                    linkerOpts(opts.split(' ').filter { it.isNotBlank() })
                }
            }
        }
    }

    sourceSets {
        // The iOS side calls Objective-C (the facade, UIKit) through cinterop.
        matching { it.name.startsWith("ios") }.configureEach { languageSettings.optIn("kotlinx.cinterop.ExperimentalForeignApi") }
        commonMain.dependencies {
            // Flows and Instant are in the public API, so both are API dependencies. Nothing else.
            api("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.10.2")
            api("org.jetbrains.kotlinx:kotlinx-datetime:0.6.2")
        }
        commonTest {
            kotlin.srcDir(contractVectors)
            dependencies {
                implementation(kotlin("test"))
                implementation("org.jetbrains.kotlinx:kotlinx-coroutines-test:1.10.2")
            }
        }
        androidMain.dependencies {
            // The Android SDK, which every call here is delegated to. Replaced by ../android
            // in this repository (settings.gradle.kts).
            api("ai.graine:inapp-android:${providers.gradleProperty("GRAINE_ANDROID_VERSION").get()}")
        }
        getByName("androidUnitTest").dependencies {
            implementation("junit:junit:4.13.2")
            // org.json is part of Android, but stubbed in JVM unit tests; the real one here.
            implementation("org.json:json:20240303")
        }
    }
}

// The simulator the iOS tests run on (`xcrun simctl list devices`), when not Kotlin's default.
providers.gradleProperty("graine.simulator").orNull?.let { device ->
    tasks.withType<org.jetbrains.kotlin.gradle.targets.native.tasks.KotlinNativeSimulatorTest>().configureEach { this.device.set(device) }
}

// Kotlin/Native libraries record their source files' paths: relative to this
// folder, never this machine's (the package guard refuses a machine path).
val relativePaths = "-Xklib-relative-path-base=${projectDir.absolutePath}"
tasks.withType<KotlinNativeCompile>().configureEach { compilerOptions.freeCompilerArgs.add(relativePaths) }
tasks.withType<KotlinCompileCommon>().configureEach { compilerOptions.freeCompilerArgs.add(relativePaths) }

android {
    namespace = "ai.graine.inapp.kmp"
    compileSdk = 36
    defaultConfig {
        // The Android SDK's own floor (its engine needs Android 7's WebView). Its ProGuard
        // rules ship inside its AAR; this layer adds no reflection and needs none.
        minSdk = 24
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
        unitTests.all { it.systemProperty("graine.version", project.version.toString()) }
        // The shared contract, where this library sits beside it in the monorepo (an exported checkout has none).
        rootProject.file("../contract").takeIf { it.isDirectory }?.let { contract ->
            unitTests.all { it.systemProperty("graine.contractDir", contract.absolutePath) }
        }
    }
}

